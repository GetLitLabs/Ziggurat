/// Output path, relative to the workspace root.
pub const BAKED_RS: &str = "crates/hcc-seal/src/baked.rs";

#[derive(Debug)]
pub enum XtaskError {
    Usage(String),
    Io(std::io::Error),
    Hygiene(&'static str),
    BadHex(String),
    Rng(getrandom::Error),
    Seal(SealError),
    Seed(hcc_seed::SeedError),
    GatesFailed(usize),
    Vendor(String),
    Modelfile(&'static str),
    Polymorph(hcc_polymorph::PolymorphError),
}

impl From<hcc_polymorph::PolymorphError> for XtaskError {
    fn from(err: hcc_polymorph::PolymorphError) -> Self {
        Self::Polymorph(err)
    }
}

impl fmt::Display for XtaskError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Usage(msg) => write!(f, "usage: {msg}"),
            Self::Io(err) => write!(f, "io: {err}"),
            Self::Hygiene(msg) => write!(f, "byte-hygiene fault: {msg}"),
            Self::BadHex(msg) => write!(f, "bad hex key file: {msg}"),
            Self::Rng(err) => write!(f, "os entropy: {err}"),
            Self::Seal(err) => write!(f, "seal: {err}"),
            Self::Seed(err) => write!(f, "seed: {err}"),
            Self::GatesFailed(n) => write!(f, "{n} gate(s) failed"),
            Self::Vendor(msg) => write!(f, "freeze-vendor: {msg}"),
            Self::Modelfile(msg) => write!(f, "modelfile: {msg}"),
            Self::Polymorph(err) => write!(f, "polymorph: {err}"),
        }
    }
}

impl std::error::Error for XtaskError {}

impl From<hcc_seed::SeedError> for XtaskError {
    fn from(err: hcc_seed::SeedError) -> Self {
        Self::Seed(err)
    }
}

impl From<std::io::Error> for XtaskError {
    fn from(err: std::io::Error) -> Self {
        Self::Io(err)
    }
}

/// Charter bytes must be UTF-8, LF only, no BOM, exactly one final newline.
pub fn hygiene(bytes: &[u8]) -> Result<(), XtaskError> {
    if bytes.starts_with(&[0xef, 0xbb, 0xbf]) {
        return Err(XtaskError::Hygiene("UTF-8 BOM present"));
    }
    if bytes.contains(&b'\r') {
        return Err(XtaskError::Hygiene("CR byte present (CRLF line endings?)"));
    }
    if !bytes.ends_with(b"\n") {
        return Err(XtaskError::Hygiene("missing final newline"));
    }
    if bytes.ends_with(b"\n\n") {
        return Err(XtaskError::Hygiene("more than one final newline"));
    }
    if std::str::from_utf8(bytes).is_err() {
        return Err(XtaskError::Hygiene("not valid UTF-8"));
    }
    Ok(())
}

pub struct SealReport {
    pub byte_len: usize,
    pub digest_hex: String,
    pub raw_b3sum_hex: String,
    pub royal: bool,
    pub baked_rs: String,
}

/// Measure the charter, verify the royal seal if given, and render `baked.rs`.
pub fn seal(charter: &[u8], royal: Option<([u8; 32], [u8; 64])>) -> Result<SealReport, XtaskError> {
    hygiene(charter)?;
    let digest = charter_digest(charter);
    let royal = royal.map(|(operator_pubkey, signature)| RoyalSeal {
        operator_pubkey,
        signature,
    });
    if let Some(royal) = &royal {
        verify_royal_seal(royal, &digest).map_err(XtaskError::Seal)?;
    }
    Ok(SealReport {
        byte_len: charter.len(),
        digest_hex: digest_hex(&digest),
        raw_b3sum_hex: blake3::hash(charter).to_hex().to_string(),
        royal: royal.is_some(),
        baked_rs: render_baked(charter.len(), &digest, royal.as_ref()),
    })
}

/// `[0x.., ...]` with eight bytes per row; `indent` is the column of the closing bracket.
fn byte_array(bytes: &[u8], indent: usize) -> String {
    let pad = " ".repeat(indent + 4);
    let rows: Vec<String> = bytes
        .chunks(8)
        .map(|chunk| {
            let cells: Vec<String> = chunk.iter().map(|b| format!("0x{b:02x},")).collect();
            format!("{pad}{}", cells.join(" "))
        })
        .collect();
    format!("[\n{}\n{}]", rows.join("\n"), " ".repeat(indent))
}

/// Deterministic `baked.rs` source. Same charter and seal give the same bytes.
pub fn render_baked(byte_len: usize, digest: &[u8; 32], royal: Option<&RoyalSeal>) -> String {
    let (import, royal_src) = match royal {
        None => ("use crate::SealConstants;", "None".to_string()),
        Some(r) => (
            "use crate::{RoyalSeal, SealConstants};",
            format!(
                "Some(RoyalSeal {{\n        operator_pubkey: {},\n        signature: {},\n    }})",
                byte_array(&r.operator_pubkey, 8),
                byte_array(&r.signature, 8),
            ),
        ),
    };
    format!(
        "// @generated by `cargo run -p hcc-xtask -- seal-charter`. Do not edit by hand.\n\
         // charter_byte_len   {byte_len}\n\
         // charter_blake3_hex {hex}\n\
         {import}\n\
         \n\
         #[rustfmt::skip]\n\
         pub const BAKED_SEAL: Option<SealConstants> = Some(SealConstants {{\n    \
         byte_len: {byte_len},\n    \
         blake3: {digest_src},\n    \
         royal: {royal_src},\n\
         }});\n",
        hex = digest_hex(digest),
        digest_src = byte_array(digest, 4),
    )
}

/// Generate an operator Ed25519 keypair from OS entropy.
/// Writes `operator.key` (0600) and `operator.pub`; refuses to overwrite.
pub fn keygen(out_dir: &Path) -> Result<[u8; 32], XtaskError> {
    let mut secret = zeroize::Zeroizing::new([0u8; 32]);
    getrandom::getrandom(secret.as_mut()).map_err(XtaskError::Rng)?;
    let key = SigningKey::from_bytes(&secret);
    let pubkey = key.verifying_key().to_bytes();
    std::fs::create_dir_all(out_dir)?;
    let secret_hex = zeroize::Zeroizing::new(format!("{}\n", hex::encode(secret.as_ref())));
    write_new_file(&out_dir.join("operator.key"), secret_hex.as_bytes())?;
    write_new_file(
        &out_dir.join("operator.pub"),
        format!("{}\n", hex::encode(pubkey)).as_bytes(),
    )?;
    Ok(pubkey)
}

/// Write a fresh Krypt RMK (stratum I): 32 raw bytes of OS entropy, mode 0600 on unix, refusing to
/// overwrite. The daemon reads it with `--rmk` (default `keys/krypt.rmk`, ignored by git).
/// Losing this file makes every key created under it unopenable; there is no recovery.
pub fn krypt_rmk(path: &Path) -> Result<(), XtaskError> {
    let mut rmk = zeroize::Zeroizing::new([0u8; hcc_krypt::KEY_LEN]);
    getrandom::getrandom(rmk.as_mut()).map_err(XtaskError::Rng)?;
    if let Some(dir) = path.parent().filter(|d| !d.as_os_str().is_empty()) {
        std::fs::create_dir_all(dir)?;
    }
    write_new_file(path, rmk.as_ref())
}

/// Sign `BLAKE3(STELE_DOMAIN || charter)` with the operator secret key.
pub fn sign_charter(charter: &[u8], secret: &[u8; 32]) -> Result<([u8; 32], [u8; 64]), XtaskError> {
    hygiene(charter)?;
    let key = SigningKey::from_bytes(secret);
    let signature = key.sign(&charter_digest(charter));
    Ok((key.verifying_key().to_bytes(), signature.to_bytes()))
}

/// Create a file that must not already exist. Mode 0600 on unix.
pub fn write_new_file(path: &Path, contents: &[u8]) -> Result<(), XtaskError> {
    let mut options = OpenOptions::new();
    options.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.mode(0o600);
    }
    let mut file = options.open(path)?;
    file.write_all(contents)?;
    Ok(())
}

/// Read a hex text file holding exactly `N` bytes.
pub fn read_hex_file<const N: usize>(path: &Path) -> Result<[u8; N], XtaskError> {
    let text = zeroize::Zeroizing::new(std::fs::read_to_string(path)?);
    let mut out = [0u8; N];
    hex::decode_to_slice(text.trim(), &mut out).map_err(|e| {
        XtaskError::BadHex(format!(
            "{}: {e} (want {} hex chars)",
            path.display(),
            N * 2
        ))
    })?;
    Ok(out)
}
